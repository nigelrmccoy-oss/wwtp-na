#!/usr/bin/env python3
"""Resolve scripts/footprint-roles.json into src/data/footprints.json (v0.3.16).

Each OSM way is fetched by id from the nigian Overpass (127.0.0.1:12346) first, with a
public mirror as fallback, and projected to the same local ENU metres as scripts/bakeGeo.mjs
(origin = plants.json location, 111320 m/deg). Data © OpenStreetMap contributors, ODbL.
"""
import json, math, sys, time, urllib.parse, urllib.request

ENDPOINTS = ['http://127.0.0.1:12346/api/interpreter', 'https://overpass-api.de/api/interpreter']
ROOT = __file__.rsplit('/scripts/', 1)[0]

def overpass(q):
    misses = 0
    for ep in ENDPOINTS:
        try:
            rq = urllib.request.Request(ep, data=urllib.parse.urlencode({'data': q}).encode(),
                                        headers={'User-Agent': 'wwtp-na-bakeFootprints/0.3.16'})
            return json.load(urllib.request.urlopen(rq, timeout=90)), ep
        except Exception as e:  # cooldown: stop after 3 misses
            misses += 1
            print('overpass miss', ep, e, file=sys.stderr)
            if misses >= 3:
                break
            time.sleep(2)
    raise SystemExit('Overpass unreachable')

def area(r):
    return abs(sum(r[i - 1][0] * r[i][1] - r[i][0] * r[i - 1][1] for i in range(len(r)))) / 2

roles = json.load(open(f'{ROOT}/scripts/footprint-roles.json'))
plants = {p['id']: p for p in json.load(open(f'{ROOT}/src/data/plants.json'))['plants']}
refs = roles['refs']
out = {'version': 'v0316', 'attribution': '© OpenStreetMap contributors (ODbL)', 'refs': refs, 'plants': {}}
for pid, spec in roles['plants'].items():
    lat0, lon0 = plants[pid]['location']['lat'], plants[pid]['location']['lon']
    mlon = 111320 * math.cos(math.radians(lat0))
    ways = {w for u in spec['units'].values() for w in u.get('ways', [])} | {spec['plantWay']}
    ids = ','.join(w.split('/')[1] for w in ways)
    data, ep = overpass(f'[out:json][timeout:60];way(id:{ids});out tags geom;')
    out['osmBase'] = data.get('osm3s', {}).get('timestamp_osm_base')
    out['overpass'] = 'nigian local Overpass' if '127.0.0.1' in ep else ep
    geom = {}
    for e in data['elements']:
        geom[f"way/{e['id']}"] = (e.get('tags', {}), [[round((g['lon'] - lon0) * mlon, 2), round(-(g['lat'] - lat0) * 111320, 2)] for g in e['geometry']])
    missing = ways - set(geom)
    if missing:
        raise SystemExit(f'{pid}: ways missing from OSM: {sorted(missing)}')
    units = {}
    for uid, u in spec['units'].items():
        osm = []
        for w in u.get('ways', []):
            tags, ring = geom[w]
            if ring[0] == ring[-1]:
                ring = ring[:-1]
            osm.append({'way': w, 'url': f'https://www.openstreetmap.org/{w}', 'areaM2': round(area(ring)),
                        'tags': {k: v for k, v in tags.items() if k in ('man_made', 'building', 'water', 'content', 'natural', 'source')},
                        'ring': ring})
        units[uid] = {k: v for k, v in u.items() if k not in ('ways', 'refs')}
        units[uid]['sources'] = [o['url'] for o in osm] + [refs[r] for r in u.get('refs', [])]
        units[uid]['osm'] = osm
    out['plants'][pid] = {
        'plantWay': spec['plantWay'], 'plantWayUrl': f"https://www.openstreetmap.org/{spec['plantWay']}",
        'units': units, 'keepHeuristic': spec.get('keepHeuristic', []), 'notes': spec.get('notes', {}),
        'excluded': spec.get('excluded', []), 'unmapped': spec.get('unmapped', []), 'conflicts': spec.get('conflicts', []),
    }
    print(pid, ep.split('/')[2], len(units), 'units', sum(len(u['osm']) for u in units.values()), 'ways')
json.dump(out, open(f'{ROOT}/src/data/footprints.json', 'w'), indent=1)

# Human-readable companion: docs/footprint-sources.md (same data, regenerated with the JSON).
lines = ['# Footprint sources (v0.3.16)', '',
         'Generated by `scripts/bakeFootprints.py` from `scripts/footprint-roles.json`. OSM outlines © OpenStreetMap contributors (ODbL), '
         f"fetched from the {out.get('overpass')} (OSM base {out.get('osmBase')}). Visual cross-check: in-app Bing Aerial (Cesium ion) nadir renders "
         '(`/home/nig/wwtp-qa/shots/v0316-*xcheck*`). No Google, Apple Maps or Street View.', '',
         '**Basis:** OSM-TAGGED = OSM tags name the role · SOURCE = a public document places the unit · '
         '**ESTIMATE** = real OSM outline but the role is inferred (or, for synthetic units, the geometry itself is estimated).', '']
for pid, P in out['plants'].items():
    lines += [f"## {pid}", '', f"Plant outline: [{P['plantWay']}]({P['plantWayUrl']})", '',
              '| Unit | Basis | OSM footprint(s) | Note | Sources |', '|---|---|---|---|---|']
    for uid, u in P['units'].items():
        ways = ', '.join(f"[{o['way']}]({o['url']}) ({o['areaM2']} m²)" for o in u['osm']) or 'none — synthetic (ESTIMATE)'
        docs = ' '.join(f'[{i + 1}]({s})' for i, s in enumerate(s for s in u['sources'] if 'openstreetmap.org' not in s))
        lines.append(f"| {uid} | {'**ESTIMATE**' if u['basis'] == 'ESTIMATE' else u['basis']} | {ways} | {u['note']} | {docs} |")
    for k, v in P['notes'].items():
        lines.append(f"| {k} | (v0.3.13 snap kept) | — | {v} | |")
    for title, key in (('Excluded OSM features', 'excluded'), ('Not in OSM (visible in ortho)', 'unmapped'), ('Conflicts between datasets', 'conflicts')):
        if P[key]:
            lines += ['', f'**{title}:**']
            lines += [f"- {e['way']}: {e['reason']}" if isinstance(e, dict) else f'- {e}' for e in P[key]]
    lines.append('')
open(f'{ROOT}/docs/footprint-sources.md', 'w').write('\n'.join(lines))
